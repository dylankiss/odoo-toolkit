"""Generate the Python requirements of each Runbot image from the Python packages the development image has.

For every image, these are the `python3-*` packages Runbot's Dockerfile installs with apt and the extra packages in
`odoo_toolkit/docker/packages.toml`. This pins them to the version the image's Ubuntu release has, like Odoo's own
`requirements.txt` pins its packages, and writes
`odoo_toolkit/multiverse_config/requirements/<image>.txt`, which `otk mv setup` installs in the virtual environments of
the image's Odoo versions. Packages Odoo's requirements pin too keep Odoo's pin, since those are installed first.

Usage: `uv run scripts/sync_requirements.py`
"""

import re
import sys
import tomllib
from collections.abc import Callable
from functools import cache
from pathlib import Path
from typing import Any

import requests

from odoo_toolkit.common import HTTP_HEADERS
from odoo_toolkit.mv.configure import IMAGE_REQUIREMENTS_DIR
from odoo_toolkit.versions import get_versions

DOCKER_DIR = Path(__file__).parent.parent / "odoo_toolkit" / "docker"
PACKAGES_FILE = DOCKER_DIR / "packages.toml"
RUNBOT_DOCKERFILES_DIR = DOCKER_DIR / "runbot"
PACKAGE_URL = "https://packages.ubuntu.com/{release}/{package}"
PACKAGE_PATTERN = re.compile(r"<h1>Package: (?P<package>\S+) \((?P<version>[^)\s]+)")
# The upstream version at the start of a Debian version like `2:0.4.27-3` or `0.9.9+dfsg-1`.
UPSTREAM_VERSION_PATTERN = re.compile(r"^(?:\d+:)?(?P<version>\d+(?:\.\d+)*)")
# The `python3-*` packages in the apt installs of Runbot's Dockerfiles, which aren't libraries of Odoo.
APT_INSTALL_PATTERN = re.compile(r"apt-get install[^\n]*(?:\\\n[^\n]*)*")
APT_PYTHON_PATTERN = re.compile(r"(?<![\w/-])python3-[a-z0-9-]+")
NOT_LIBRARIES = {"python3-dev", "python3-pip", "python3-setuptools", "python3-venv", "python3-wheel"}
# Odoo's Debian package of phonenumbers, which Runbot installs over Ubuntu's.
PHONENUMBERS_DEB_PATTERN = re.compile(r"python3-phonenumbers_(?P<version>\d+(?:\.\d+)*)-")
TIMEOUT = 30
HEADER = (
    "# Generated by `scripts/sync_requirements.py` from `odoo_toolkit/docker/packages.toml`, do not modify.\n"
    "# The versions of the {release} packages of the {image} image.\n"
)

type VersionGetter = Callable[[str, str], str]


def get_upstream_version(debian_version: str) -> str:
    """Convert a Debian package version into the upstream version PyPI uses, like `2:0.4.27-3` into `0.4.27`."""
    match = UPSTREAM_VERSION_PATTERN.match(debian_version)
    if not match:
        msg = f"Can't get the upstream version of {debian_version}."
        raise ValueError(msg)
    return match.group("version")


@cache
def get_ubuntu_version(release: str, package: str) -> str:
    """Get the version of a package in an Ubuntu release, including its updates.

    :param release: The Ubuntu release, like `noble`.
    :param package: The package, like `python3-ldap`.
    :raises ValueError: If the release doesn't have the package.
    :return: The Debian version, like `3.4.4-1build2`.
    """
    response = requests.get(PACKAGE_URL.format(release=release, package=package), headers=HTTP_HEADERS, timeout=TIMEOUT)
    response.raise_for_status()
    match = PACKAGE_PATTERN.search(response.text)
    if not match or match.group("package") != package:
        msg = f"Ubuntu {release} has no package {package}."
        raise ValueError(msg)
    return match.group("version")


def get_runbot_packages(image: str) -> tuple[list[str], str | None]:
    """Get the Python packages Runbot's Dockerfile of an image installs with apt.

    :param image: The Runbot image name, like `Docker19`.
    :return: The apt packages, and the version of phonenumbers Runbot installs over Ubuntu's, if any.
    """
    dockerfile = (RUNBOT_DOCKERFILES_DIR / f"{image}.Dockerfile").read_text(encoding="utf-8")
    packages = {
        package
        for install in APT_INSTALL_PATTERN.findall(dockerfile)
        for package in APT_PYTHON_PATTERN.findall(install)
        if package not in NOT_LIBRARIES
    }
    phonenumbers = PHONENUMBERS_DEB_PATTERN.search(dockerfile)
    return sorted(packages), phonenumbers.group("version") if phonenumbers else None


def get_pypi_name(package: str, names: dict[str, str]) -> str:
    """Get the PyPI name of an apt package: the name in `names`, or the apt name without `python3-`."""
    return names.get(package, package.removeprefix("python3-"))


def render_requirements(
    image: str,
    release: str,
    config: dict[str, Any],
    get_version: VersionGetter = get_ubuntu_version,
) -> str:
    """Render the requirements file of an image.

    :param image: The Runbot image name, like `Docker19`.
    :param release: The Ubuntu release of the image, like `noble`.
    :param config: The contents of `packages.toml`.
    :param get_version: Returns the Debian version of a package, given the release and the package.
    :return: The requirements, pinned to the versions of the apt packages, and the pip packages as they are.
    """
    runbot_apt, phonenumbers_version = get_runbot_packages(image)
    sections: list[dict[str, list[str]]] = [config.get("common", {}), config.get(image, {})]
    apt = sorted({*runbot_apt, *(package for section in sections for package in section.get("apt", []))})
    pip = sorted({package for section in sections for package in section.get("pip", [])})
    names: dict[str, str] = config.get("pypi", {})
    overrides: dict[str, str] = config.get("versions", {})
    pinned: list[tuple[str, str]] = []
    for package in apt:
        if package in overrides:
            version = overrides[package]
        elif package == "python3-phonenumbers" and phonenumbers_version:
            version = phonenumbers_version
        else:
            version = get_upstream_version(get_version(release, package))
        pinned.append((f"{get_pypi_name(package, names)}=={version}", package))
    pinned.sort()
    # Align the comments naming the apt packages.
    width = max((len(requirement) for requirement, _ in pinned), default=0)
    lines = [f"{requirement:<{width}}  # {package}" for requirement, package in pinned]
    return HEADER.format(release=release, image=image) + "\n".join(lines + pip) + "\n"


def main() -> int:
    """Write the requirements file of every image."""
    with PACKAGES_FILE.open("rb") as packages_file:
        config = tomllib.load(packages_file)
    releases = {version.image: version.ubuntu for version in get_versions().values()}
    IMAGE_REQUIREMENTS_DIR.mkdir(exist_ok=True)
    for image, release in releases.items():
        (IMAGE_REQUIREMENTS_DIR / f"{image}.requirements").write_text(
            render_requirements(image, release, config), encoding="utf-8"
        )
        print(f"Wrote the requirements of {image} for Ubuntu {release}.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
